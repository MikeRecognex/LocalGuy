// Canonical spelling for tags, applied wherever tags are computed.
//
// Two producers disagreed on spelling: the regex taxonomy emitted British
// `-isation`, the LLM classifier emitted American `-ization`. That split the same
// concept across two pages — /tags/quantisation/ held 654 posts and
// /tags/quantization/ another 214. American wins because it is what the source
// material and the wider ML ecosystem use, and because it was already dominant
// here (inference-optimization 324 posts vs inference-optimisation 1).
//
// The rule is deliberately scoped to the two stems that actually occur rather
// than a general s -> z rewrite. A blanket rule would corrupt real tags:
// `supervised-fine-tuning-dataset` and `audio-denoising` both contain an
// innocent "is" and must survive untouched.
const SPELLING = /(optimi|quanti)s/g;

// Distinct concepts that arrived under more than one name.
//
// The separator-variant block below is generated by scripts/find-tag-collisions.js,
// which finds tags that are identical once every non-alphanumeric character is
// stripped. Left unmerged these split one subject over two half-empty pages:
// /tags/qwen-3-8-27b/ held 5 posts and /tags/qwen3-8-27b/ another 4, for one model.
//
// The merge is listed explicitly rather than derived from a rule. The obvious rule —
// insert a hyphen between a letter-run and a digit-run — would rewrite `gpt4all` to
// `gpt-4-all` and `lfm2` to `lfm-2`, breaking real product names. That is the same
// trap the SPELLING regex above is deliberately scoped to avoid.
//
// The surviving spelling is the more frequent one, which in every case here also
// matches the slug convention already used elsewhere (dots and spaces become hyphens,
// as in llama.cpp -> llama-cpp). Re-run the detector after any retag; new tags arrive
// from an open-ended LLM vocabulary and will collide again.

function canonicalTag(tag) {
  if (typeof tag !== "string") return tag;
  const normalised = tag.replace(SPELLING, "$1z");
  // Look up case-insensitively: the LLM emits the same slug in mixed casing
  // ("MediaTek", "mediatek"), and a case-sensitive lookup would let one variant
  // past the alias map and back onto its own page.
  return EXPLICIT[normalised.toLowerCase()] || normalised;
}

module.exports = { canonicalTag };
